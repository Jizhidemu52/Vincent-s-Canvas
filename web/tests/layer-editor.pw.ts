import { test, expect, type Page } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const open = async (page: Page) => {
    const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto("/tests/layer-editor.fixture.html");
    await expect(page.getByRole("button", { name: "导出合成 PNG" })).toBeEnabled();
    await expect.poll(() => pixel(page, 32, 32)).toEqual([0, 255, 0, 255]);
    return errors;
};
const pixel = (page: Page, x: number, y: number) => page.locator("canvas").evaluate((canvas: HTMLCanvasElement, point) => [...canvas.getContext("2d")!.getImageData(point.x, point.y, 1, 1).data], { x, y });
const value = (page: Page) => page.evaluate(() => (window as any).layerEditorFixture.value);
const fixture = (page: Page, method: string) => page.evaluate(method => (window as any).layerEditorFixture[method](), method);

test("same geometry renders preview and PNG with alpha, original byte hash retained", async ({ page }) => {
    const errors = await open(page);
    await expect.poll(() => pixel(page, 20, 20)).toEqual([0, 0, 255, 255]);
    await expect.poll(() => pixel(page, 2, 2)).toEqual([255, 0, 0, 255]);
    await page.getByRole("checkbox", { name: "显示 红色底图" }).uncheck();
    await expect.poll(() => pixel(page, 2, 2)).toEqual([0, 0, 0, 0]);
    const originalPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: "下载 蓝色方块 原件" }).click();
    const original = await originalPromise, bytes = await readFile((await original.path())!);
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(await page.evaluate(() => (window as any).layerEditorFixture.digests.blue));
    expect(original.suggestedFilename()).toBe("02-蓝色方块.png");
    const pngPromise = page.waitForEvent("download"); await page.getByRole("button", { name: "导出合成 PNG" }).click();
    const png = await pngPromise, pngBytes = await readFile((await png.path())!);
    const pixels = await page.evaluate(async base64 => {
        const binary = atob(base64), bytes = Uint8Array.from(binary, character => character.charCodeAt(0));
        const image = await createImageBitmap(new Blob([bytes], { type: "image/png" }));
        const canvas = document.createElement("canvas"); canvas.width = image.width; canvas.height = image.height;
        const context = canvas.getContext("2d")!; context.drawImage(image, 0, 0); image.close();
        return { size: [canvas.width, canvas.height], corner: [...context.getImageData(2, 2, 1, 1).data], center: [...context.getImageData(32, 32, 1, 1).data] };
    }, pngBytes.toString("base64"));
    expect(pixels).toEqual({ size: [64, 64], corner: [0, 0, 0, 0], center: [0, 255, 0, 255] });
    const requests = await page.evaluate(() => (window as any).layerEditorFixture.requests);
    expect(requests.every((request: any) => request.method === "GET" && request.headers["x-canvas-owner-id"] === "synthetic-owner-a")).toBe(true);
    expect(errors).toEqual([]);
});
