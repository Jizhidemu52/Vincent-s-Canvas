import { test, expect } from "./fixtures";
import { generalPromptTemplates } from "../../shared/general-prompt-templates";

test("catalog copy shows an inline success for 1.2s and preserves failure feedback", async ({ page, context, api }) => {
    await context.grantPermissions(["clipboard-read", "clipboard-write"]);
    await page.goto("/prompts");
    const item = generalPromptTemplates[0];
    const card = page.locator(`[data-general-prompt-id="${item.id}"]`);
    await expect(card).toBeVisible();
    await page.clock.install();
    await page.clock.pauseAt(new Date());
    await card.getByRole("button", { name: "复制提示词", exact: true }).click();
    await expect(card.getByRole("button", { name: "已复制 ✓", exact: true })).toBeVisible();
    expect((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, "\n")).toBe(item.prompt);
    await page.clock.runFor(1199);
    await expect(card.getByRole("button", { name: "已复制 ✓", exact: true })).toBeVisible();
    await page.clock.runFor(1);
    await expect(card.getByRole("button", { name: "复制提示词", exact: true })).toBeVisible();
    await page.clock.resume();
    await card.getByRole("button", { name: `查看完整提示词：${item.title}`, exact: true }).click();
    const drawer = page.getByRole("dialog", { name: item.title, exact: true });
    await drawer.getByRole("button", { name: "复制提示词", exact: true }).click();
    await expect(drawer.getByRole("button", { name: "已复制 ✓", exact: true })).toBeVisible();
    await expect(drawer.getByRole("button", { name: "复制提示词", exact: true })).toBeVisible();
    await page.evaluate(() => {
        navigator.clipboard.writeText = async () => { throw new DOMException("Permission denied", "NotAllowedError"); };
        document.execCommand = () => false;
        window.prompt = () => null;
    });
    await drawer.getByRole("button", { name: "复制提示词", exact: true }).click();
    await expect(page.getByText("复制失败，请检查浏览器剪贴板权限后重试", { exact: true })).toBeVisible();
    await expect(drawer.getByRole("button", { name: "已复制 ✓", exact: true })).toHaveCount(0);
    expect(api.submissions).toEqual([]);
});

test("personal login renders required and server errors inline at desktop and mobile widths", async ({ page, context, api }, info) => {
    const requests: unknown[] = [];
    await context.route("**/api/auth/methods", route => route.fulfill({ json: { password: true, wecom: false, wecomLoginUrl: null } }));
    await context.route("**/api/auth/login", route => {
        requests.push(route.request().postDataJSON());
        return route.fulfill({ status: 423, json: { message: "账号已锁定，请联系管理员" } });
    });
    await page.setViewportSize({ width: 1366, height: 768 });
    await page.goto("/login");
    const submit = page.getByRole("button", { name: "登录工作台", exact: true });
    const administrator = page.getByRole("button", { name: "管理员入口", exact: true });
    await expect(submit).toBeVisible();
    expect(await submit.evaluate(element => getComputedStyle(element).backgroundColor)).toBe("rgb(39, 39, 36)");
    const submitBox = (await submit.boundingBox())!, adminBox = (await administrator.boundingBox())!;
    expect(adminBox.y - submitBox.y - submitBox.height).toBeGreaterThanOrEqual(12);
    await page.getByRole("button", { name: "登录工作台", exact: true }).click();
    const account = page.getByLabel("个人账号", { exact: true });
    const password = page.getByLabel("登录密码", { exact: true });
    await expect(account).toHaveAttribute("aria-invalid", "true");
    await expect(password).toHaveAttribute("aria-invalid", "true");
    await expect(page.locator("#personal-login-identifier-error")).toHaveText("请输入个人账号");
    await expect(page.locator("#personal-login-password-error")).toHaveText("请输入密码");
    expect(requests).toEqual([]);
    await page.screenshot({ path: info.outputPath("login-required-1366.png") });
    await account.fill(" designer ");
    await expect(page.locator("#personal-login-identifier-error")).toHaveCount(0);
    await expect(page.locator("#personal-login-password-error")).toBeVisible();
    await password.fill(" original password ");
    await page.getByRole("button", { name: "登录工作台", exact: true }).click();
    await expect(page.locator("form").getByRole("alert")).toHaveText("账号已锁定，请联系管理员");
    await expect(page.locator(".ant-message-notice")).toHaveCount(0);
    expect(requests).toEqual([{ identifier: "designer", password: " original password ", portal: "designer" }]);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("login-server-error-390.png"), fullPage: true });
    await account.fill("");
    await password.fill("");
    await page.getByTestId("language-switch").click();
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page.locator("#personal-login-identifier-error")).toHaveText("Enter your personal account");
    await expect(page.locator("#personal-login-password-error")).toHaveText("Enter your password");
    expect(requests).toHaveLength(1);
    expect(api.submissions).toEqual([]);
});
