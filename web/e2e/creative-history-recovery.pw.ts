import { createHash } from "node:crypto";
import { test, expect, IMAGE } from "./fixtures";
import { activeWorkbench, readWorkspaceRecords } from "./headless-workbench";

for (const failedWrite of ["history-record:", "history-index:"]) test(`garment result survives ${failedWrite} failure and repairs only local history`, async ({ page, api }, info) => {
    api.taskStatus = "paused";
    await page.goto("/creative/garment-colorway");
    const pane = activeWorkbench(page);
    await pane.getByLabel("上传服装参考图", { exact: true }).setInputFiles({ name: "original-garment.png", mimeType: "image/png", buffer: IMAGE });
    await pane.locator("button.cs-generate").click();
    await expect(pane.getByRole("button", { name: "刷新进度", exact: true })).toBeVisible();
    expect(api.submissions).toHaveLength(1);
    const task = [...api.tasks.values()][0]!;
    const requestId = task.requestId;
    const originalBytes = api.assetBytes.get(task.id)!;
    await page.evaluate(prefix => {
        const put = IDBObjectStore.prototype.put;
        (window as any).restoreCreativeHistoryWrites = () => { IDBObjectStore.prototype.put = put; };
        IDBObjectStore.prototype.put = function(value: any, key?: IDBValidKey) {
            const terminal = prefix === "history-index:" ? value.entries?.some((entry: any) => entry.successCount === 1) : value.successCount === 1;
            if (this.name === "creative_scene_workspaces" && String(key).startsWith(prefix) && terminal) throw new DOMException("isolated terminal history failure", "QuotaExceededError");
            return put.call(this, value, key);
        };
    }, failedWrite);
    task.status = "success";
    task.resultUrls = [`/api/assets/${task.id}/content`];
    await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect(pane.getByRole("button", { name: "下载原图", exact: true })).toBeVisible();
    await expect(pane.getByText(/生成结果仍保留在页面，但本地记录保存失败/)).toBeVisible();
    await expect(pane.getByText("暂时无法获取进度，稍后会自动更新。", { exact: true })).toHaveCount(0);
    await expect(pane.getByRole("button", { name: "暂停获取进度", exact: true })).toHaveCount(0);
    const resultImage = pane.getByRole("img", { name: "服装配色结果 1", exact: true });
    await expect(resultImage).toBeVisible();
    await expect.poll(() => resultImage.evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(256);
    const downloadEvent = page.waitForEvent("download");
    await pane.getByRole("button", { name: "下载原图", exact: true }).click();
    const download = await downloadEvent;
    const stream = await download.createReadStream();
    const bytes: Buffer[] = [];
    for await (const chunk of stream!) bytes.push(Buffer.from(chunk));
    expect(createHash("sha256").update(Buffer.concat(bytes)).digest("hex")).toBe(createHash("sha256").update(originalBytes).digest("hex"));
    await page.screenshot({ path: info.outputPath("success-with-history-warning-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await resultImage.scrollIntoViewIfNeeded();
    await expect(resultImage).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
    await page.screenshot({ path: info.outputPath("success-with-history-warning-mobile.png"), fullPage: true });
    const reads = api.taskReads.length;
    await page.evaluate(() => { (window as any).restoreCreativeHistoryWrites(); window.dispatchEvent(new Event("focus")); });
    await expect.poll(async () => (await readWorkspaceRecords<any>(page, "creative_scene_workspaces")).filter(record => record.key.startsWith("history-index:")).flatMap(record => record.value.entries).map(entry => ({ success: entry.successCount, unresolved: entry.unresolvedCount }))).toEqual([{ success: 1, unresolved: 0 }]);
    await expect(pane.getByText(/生成结果仍保留在页面，但本地记录保存失败/)).toHaveCount(0);
    const logs = (await readWorkspaceRecords<any>(page, "creative_scene_workspaces")).filter(record => record.key.startsWith("history-record:"));
    expect(logs).toHaveLength(1);
    expect(logs[0]!.value.results[0]).toMatchObject({ status: "success", taskId: task.id, requestId, image: { sourceTaskId: task.id } });
    expect(api.taskReads).toHaveLength(reads);
    expect(api.submissions).toHaveLength(1);
    await page.reload();
    await expect(activeWorkbench(page).getByRole("button", { name: "下载原图", exact: true })).toBeVisible();
    await expect(activeWorkbench(page).getByText(/生成结果仍保留在页面，但本地记录保存失败/)).toHaveCount(0);
    expect(api.submissions).toHaveLength(1);
    expect(api.submissions[0]!.requestId).toBe(requestId);
    await activeWorkbench(page).getByRole("button", { name: "下载原图", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: info.outputPath("success-after-history-repair-mobile.png"), fullPage: true });
});
