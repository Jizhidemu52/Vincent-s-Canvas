import { readFile } from "node:fs/promises";
import { strFromU8, unzipSync } from "fflate";
import type { Route } from "@playwright/test";
import { test, expect, newCanvas, uploadImage, IMAGE } from "./fixtures";

test("node prompt module 404 is isolated without reloading the canvas or discarding the open draft", async ({ page, context, api }, testInfo) => {
    const moduleFailures: string[] = [];
    let pendingModule: Route | undefined;
    let documentLoads = 0;
    page.on("request", request => { if (request.resourceType() === "document") documentLoads++; });
    await page.route("**/src/components/canvas/canvas-node-prompt-panel.tsx*", route => {
        moduleFailures.push(route.request().url());
        pendingModule = route;
    });
    const projectId = await newCanvas(page);
    await uploadImage(page, "protected-original.png");
    await expect.poll(() => api.document(projectId)?.nodes.length).toBe(1);
    const originalNode = page.locator(`[data-node-id="${api.document(projectId)!.nodes[0].id}"]`);
    await expect(originalNode.locator("img")).toBeVisible();
    await page.getByRole("button", { name: "展开创建面板", exact: true }).click();
    const draft = page.getByTestId("canvas-quick-generate-panel").getByRole("textbox", { name: "描述图像", exact: true });
    const canvasUrl = page.url();
    await page.getByRole("button", { name: "更多工具", exact: true }).click();
    await page.getByRole("menuitem", { name: "图片节点", exact: true }).click();
    await expect.poll(() => moduleFailures.length).toBe(1);
    // Selection can intentionally rebind the Create panel. Type only after that
    // transition, while the optional node module is still genuinely in flight.
    await expect(draft).toHaveValue("");
    await draft.fill("尚未提交的创作草稿，不应因另一个模块失败而丢失");
    const mountedDraft = (await draft.elementHandle())!;
    const mountedCanvas = (await page.locator("main.cw-workspace").elementHandle())!;
    await pendingModule!.fulfill({ status: 404, contentType: "text/plain", body: "Module no longer available in this release" });
    await expect(page.getByText("Unexpected Application Error!", { exact: true })).toHaveCount(0);
    const notice = page.getByRole("alert").filter({ hasText: "节点编辑模块暂不可用" });
    await expect(notice).toBeVisible();
    expect(await mountedCanvas.evaluate(element => element.isConnected)).toBe(true);
    expect(await mountedDraft.evaluate(element => element.isConnected)).toBe(true);
    await expect(draft).toHaveValue("尚未提交的创作草稿，不应因另一个模块失败而丢失");
    await expect(originalNode.locator("img")).toBeVisible();
    await expect(page.getByRole("button", { name: "上传素材", exact: true })).toBeEnabled();
    const recovery = notice.getByRole("link", { name: "新标签页恢复", exact: true });
    await expect(recovery).toHaveAttribute("href", canvasUrl);
    await expect(recovery).toHaveAttribute("target", "_blank");
    await expect(notice).toContainText("不代表已保存或已同步");
    const downloadPromise = page.waitForEvent("download");
    await notice.getByRole("button", { name: "备份画布", exact: true }).click();
    const archive = await downloadPromise;
    await archive.saveAs(testInfo.outputPath("module-failure-backup.zip"));
    const files = unzipSync(await readFile((await archive.path())!));
    const payload = JSON.parse(strFromU8(files["projects.json"]!));
    const projects = Array.isArray(payload) ? payload : payload.projects;
    expect(projects).toHaveLength(1);
    expect(projects[0].project.nodes).toHaveLength(2);
    expect(projects[0].project.nodes[0].title).toBe("protected-original.png");
    expect(Object.values(files).some(bytes => Buffer.from(bytes).equals(IMAGE))).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("module-failure-contained.png"), animations: "disabled", fullPage: true });
    await expect(draft).toHaveValue("尚未提交的创作草稿，不应因另一个模块失败而丢失");
    const reopened = context.waitForEvent("page");
    await recovery.click();
    const newPage = await reopened;
    await newPage.waitForURL(canvasUrl);
    await expect(newPage.getByTestId("canvas-readonly-session")).toBeVisible();
    await expect(newPage.getByText("此画布正在另一标签页编辑。当前为只读快照，不会覆盖那边的修改。", { exact: true })).toBeVisible();
    await expect(page).toHaveURL(canvasUrl);
    await expect(page.locator('[data-canvas-edit-blocked="true"]')).toHaveCount(0);
    expect(await mountedCanvas.evaluate(element => element.isConnected)).toBe(true);
    await expect(draft).toHaveValue("尚未提交的创作草稿，不应因另一个模块失败而丢失");
    await newPage.close();
    await notice.getByRole("button", { name: "关闭编辑区", exact: true }).click();
    await expect(notice).toHaveCount(0);
    await expect(page.locator("[data-node-id]")).toHaveCount(2);
    expect(documentLoads).toBe(1);
    expect(moduleFailures).toHaveLength(1);
    expect(api.submissions).toEqual([]);
    expect(api.batchSubmissions).toEqual([]);
});
