import { resolve } from "node:path";
import { test, expect, IMAGE } from "./fixtures";

test("画布视频标题可拖动，低缩放保留静态首帧且不加载原视频", async ({ page, context, api }, info) => {
    const id = "video-node-integration", now = new Date().toISOString();
    const assetId = "22222222-2222-4222-8222-222222222222";
    const content = `/api/assets/${assetId}/content`;
    const node = { id: "video", type: "video", title: "样衣展示视频", width: 320, height: 180, position: { x: 630, y: 300 }, metadata: { content, serverAssetId: assetId, status: "success", durationMs: 280, naturalWidth: 320, naturalHeight: 180 } };
    const document = { id, title: "视频集成回归", createdAt: now, updatedAt: now, nodes: [node], connections: [], groups: [], viewport: { x: 0, y: 0, k: 1 }, backgroundMode: "dots", showImageInfo: false, chatSessions: [], activeChatId: null };
    api.documents.set(id, { id, revision: 1, deleted: false, document, updatedAt: now });
    let originals = 0;
    await context.route(`**${content}`, route => { originals++; return route.fulfill({ contentType: "video/mp4", path: resolve(import.meta.dirname, "media/video.mp4") }); });
    await context.route(`**/api/assets/${assetId}/thumb*`, route => route.fulfill({ contentType: "image/png", body: IMAGE, headers: { "X-Canvas-Media-Duration-Ms": "280" } }));
    await page.goto(`/canvas/${id}`);
    const videoNode = page.locator('[data-node-id="video"]');
    const title = page.locator('[data-node-title="video"]');
    await expect(videoNode.getByLabel("播放视频", { exact: true })).toHaveAttribute("poster", /^blob:/);
    await expect(title).toBeVisible();
    expect(originals).toBe(0);
    const bounds = (await title.boundingBox())!;
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width / 2 + 90, bounds.y + bounds.height / 2 + 45, { steps: 8 });
    await page.mouse.up();
    await page.screenshot({ path: info.outputPath("video-after-title-drag.png") });
    await expect.poll(() => api.document(id)?.nodes[0].position).toEqual({ x: 720, y: 345 });
    const toolbarBounds = (await page.getByRole("toolbar", { name: "节点工具栏", exact: true }).boundingBox())!;
    expect(toolbarBounds.y + toolbarBounds.height).toBeLessThan((await title.boundingBox())!.y);
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "画布缩放与视图", exact: true }).click();
    const scale = page.getByRole("spinbutton", { name: "画布缩放百分比", exact: true });
    await scale.fill("25"); await scale.press("Enter");
    await expect(videoNode.locator("video")).toHaveCount(0);
    await expect(videoNode.getByAltText("视频封面", { exact: true })).toBeVisible();
    await expect(title).toBeVisible();
    expect((await title.boundingBox())!.width).toBeCloseTo(bounds.width, 0);
    await page.getByRole("button", { name: "画布缩放与视图", exact: true }).click();
    const smallTitle = (await title.boundingBox())!;
    await page.mouse.move(smallTitle.x + smallTitle.width / 2, smallTitle.y + smallTitle.height / 2);
    await page.mouse.down();
    await page.mouse.move(smallTitle.x + smallTitle.width / 2 + 20, smallTitle.y + smallTitle.height / 2 + 10, { steps: 5 });
    await page.mouse.up();
    await expect.poll(() => api.document(id)?.nodes[0].position).toEqual({ x: 800, y: 385 });
    await expect(videoNode.locator("video")).toHaveCount(0);
    expect(originals).toBe(0);
    expect(api.submissions).toHaveLength(0);
    expect(api.batchSubmissions).toHaveLength(0);
    await page.screenshot({ path: info.outputPath("canvas-video-25-percent-poster.png") });
});
