test("delayed connection keeps all editing disabled until the saved discussion is restored", async ({ page, context, api }, info) => {
    let holdModels = false;
    let releaseModels: (() => void) | undefined;
    const modelGate = new Promise<void>(resolve => { releaseModels = resolve; });
    await context.route("**/api/models", async route => { if (holdModels) await modelGate; await route.fulfill({ json: catalog }); });
    await newCanvas(page);
    await page.getByRole("button", { name: "打开设计讨论", exact: true }).click();
    const panel = page.getByRole("complementary", { name: "设计讨论面板" });
    await expect(panel.getByRole("button", { name: "发送讨论", exact: true })).toBeEnabled();
    await panel.locator(".discussion-settings > summary").click();
    await panel.getByRole("combobox", { name: "生成类型", exact: true }).selectOption("video");
    await panel.getByRole("textbox", { name: "输入设计需求" }).fill("已保存的视频讨论需求");
    await panel.getByRole("button", { name: "收起讨论面板" }).click();
    holdModels = true;
    await page.reload();
    await page.getByRole("button", { name: "打开设计讨论", exact: true }).click();
    await expect(panel.getByRole("status")).toContainText("正在恢复讨论");
    const writableControls = panel.locator("input:not([type=hidden]), select, textarea, button:not([aria-label='收起讨论面板'])");
    for (const control of await writableControls.all()) await expect(control).toBeDisabled();
    await page.screenshot({ path: info.outputPath("discussion-connection-loading.png"), animations: "disabled" });
    holdModels = false;
    releaseModels?.();
    await expect(panel.getByRole("button", { name: "发送讨论", exact: true })).toBeEnabled();
    await panel.locator(".discussion-settings > summary").click();
    await expect(panel.getByRole("combobox", { name: "生成类型", exact: true })).toHaveValue("video");
    await expect(panel.getByRole("textbox", { name: "输入设计需求" })).toHaveValue("已保存的视频讨论需求");
    await panel.getByRole("textbox", { name: "输入设计需求" }).fill("恢复后可以继续修改");
    await expect(panel.getByRole("textbox", { name: "输入设计需求" })).toHaveValue("恢复后可以继续修改");
    expect(api.submissions).toHaveLength(0);
});
