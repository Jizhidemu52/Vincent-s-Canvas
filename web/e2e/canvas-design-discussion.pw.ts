for (const failure of [
    { status: "failed", httpStatus: 400, reason: "视频首帧需要公开素材 URL", label: "提交失败" },
    { status: "uncertain", httpStatus: 503, reason: "提交回执暂不可用", label: "提交待确认" },
    { status: "paused", httpStatus: 200, reason: "模型任务已暂停", label: "任务已暂停" },
    { status: "cancelled", httpStatus: 200, reason: "模型任务已取消", label: "任务已取消" },
]) test(`proposal ${failure.status} stays visible, closable and never resubmits`, async ({ page, context, api }, info) => {
    await context.route("**/api/models", route => route.fulfill({ json: catalog }));
    await context.route("**/api/chat/responses", route => route.fulfill({ json: { content: JSON.stringify({ message: "请确认测试方案。", questions: [], proposals: [fixtureProposal], sources: [], trendStatus: "隔离回归" }), toolCalls: [] } }));
    await context.route("**/api/tasks", route => {
        if (route.request().method() !== "POST") return route.fallback();
        const body = route.request().postDataJSON();
        api.submissions.push(body);
        if (failure.httpStatus !== 200) return route.fulfill({ status: failure.httpStatus, json: { message: failure.reason } });
        const task = { ...body, id: "20000000-0000-4000-8000-000000000001", userId: route.request().headers()["x-canvas-owner-id"], status: failure.status, resultUrls: [], failureReason: failure.reason };
        api.tasks.set(task.id, task);
        return route.fulfill({ json: { task } });
    });
    await context.route("**/api/tasks/by-request/**", route => route.fulfill({ status: 404, json: { message: "原请求暂无服务器任务" } }));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await newCanvas(page);
    await page.getByRole("button", { name: "打开设计讨论", exact: true }).click();
    const panel = page.getByRole("complementary", { name: "设计讨论面板" });
    await expect(panel.getByRole("button", { name: "发送讨论", exact: true })).toBeEnabled();
    await panel.getByRole("combobox", { name: "生成类型", exact: true }).selectOption("video");
    await panel.getByRole("textbox", { name: "输入设计需求" }).fill("生成三个针织服装展示视频，保持针织材质，缓慢推近。");
    await panel.getByRole("combobox", { name: "方案数量", exact: true }).selectOption("1");
    await panel.getByRole("combobox", { name: "生成数量", exact: true }).selectOption("3");
    await panel.getByRole("button", { name: "给我方案", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "可选设计方向 · 1 个方案" });
    const generate = dialog.getByRole("button", { name: "按选中方案生成 3 个视频", exact: true });
    await generate.click();
    await expect(dialog.getByRole("alert")).toContainText(failure.reason);
    await expect(dialog.getByRole("alert")).toContainText("不会重复生成");
    await expect(dialog.locator(".proposal-receipt")).toContainText(failure.label);
    await expect(dialog.getByRole("alert")).toBeInViewport({ ratio: 1 });
    expect(api.submissions).toHaveLength(1);
    await generate.click();
    await expect(dialog.getByRole("alert")).toContainText(failure.reason);
    expect(api.submissions).toHaveLength(1);
    await expect(page.locator(".dd-notice").filter({ hasText: "已提交" })).toHaveCount(0);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(dialog.getByRole("alert")).toBeInViewport({ ratio: 1 });
    await expect(dialog.getByRole("button", { name: "关闭方案选择" })).toBeInViewport({ ratio: 1 });
    await page.screenshot({ path: info.outputPath(`proposal-${failure.status}-mobile.png`), animations: "disabled" });
    await dialog.getByRole("button", { name: "关闭方案选择" }).click();
    await expect(dialog).not.toBeVisible();
    await expect(panel.locator(".studio-batch")).toContainText("已记录 1 个请求");
    await page.reload();
    await page.getByRole("button", { name: "打开设计讨论", exact: true }).click();
    await expect(panel.locator(".studio-batch")).toBeEnabled();
    await panel.locator(".studio-batch").click();
    await expect(dialog.locator(".proposal-receipt")).toContainText(failure.reason);
    await generate.click();
    await expect(dialog.getByRole("alert")).toContainText(failure.reason);
    expect(api.submissions).toHaveLength(1);
    await page.keyboard.press("Escape");
    await expect(dialog).not.toBeVisible();
});

test("delayed connection keeps all editing disabled until the saved discussion is restored", async ({ page, context, api }, info) => {
    let holdModels = false;
    let releaseModels: (() => void) | undefined;
    const modelGate = new Promise<void>(resolve => { releaseModels = resolve; });
    await context.route("**/api/models", async route => { if (holdModels) await modelGate; await route.fulfill({ json: catalog }); });
    await newCanvas(page);
    await page.getByRole("button", { name: "打开设计讨论", exact: true }).click();
    const panel = page.getByRole("complementary", { name: "设计讨论面板" });
    await expect(panel.getByRole("button", { name: "发送讨论", exact: true })).toBeEnabled();
    await panel.getByRole("combobox", { name: "生成类型", exact: true }).selectOption("video");
    await panel.getByRole("textbox", { name: "输入设计需求" }).fill("已保存的视频讨论需求");
    await panel.getByRole("button", { name: "收起讨论面板" }).click();
    holdModels = true;
    await page.reload();
    await page.getByRole("button", { name: "打开设计讨论", exact: true }).click();
    await expect(panel.getByRole("status")).toContainText("正在恢复讨论");
    const writableControls = panel.locator("input:not([type=hidden]), select, textarea, button:not([aria-label='收起讨论面板'])");
    for (const control of await writableControls.all()) await expect(control).toBeDisabled();
    await page.screenshot({ path: info.outputPath("discussion-connection-loading.png"), animations: "disabled" });
    holdModels = false;
    releaseModels?.();
    await expect(panel.getByRole("button", { name: "发送讨论", exact: true })).toBeEnabled();
    await expect(panel.getByRole("combobox", { name: "生成类型", exact: true })).toHaveValue("video");
    await expect(panel.getByRole("textbox", { name: "输入设计需求" })).toHaveValue("已保存的视频讨论需求");
    await panel.getByRole("textbox", { name: "输入设计需求" }).fill("恢复后可以继续修改");
    await expect(panel.getByRole("textbox", { name: "输入设计需求" })).toHaveValue("恢复后可以继续修改");
    expect(api.submissions).toHaveLength(0);
});
