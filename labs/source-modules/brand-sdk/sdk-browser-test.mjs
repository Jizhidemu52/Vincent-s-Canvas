import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined, headless: true });
await fs.mkdir(path.join(root, 'qa'), { recursive: true });
const context = await browser.newContext({ viewport: { width: 1200, height: 900 } });
const report = { passed: false, checks: [], errors: [], external: [], actual: 'Source sticky-note plugin built by source SDK buildPlugin; React 19.2.4', adapter: 'Node context/updateMetadata/localStorage in sdk-host.tsx; not original host persistence' };
await context.route('**/*', route => { const u = new URL(route.request().url()); if (['http:', 'https:'].includes(u.protocol) && u.origin !== 'http://127.0.0.1:4331') { report.external.push(u.href); return route.abort(); } return route.continue(); });
const page = await context.newPage(); page.on('pageerror', e => report.errors.push(e.message));
const state = async () => JSON.parse(await page.locator('#metadata').innerText());
try {
  await page.goto('http://127.0.0.1:4331/');
  await page.getByText('双击编辑便利贴', { exact: true }).waitFor();
  report.checks.push('Original compiled plugin loads before host runtime injection and renders through host React.');
  await page.locator('#plugin-node').dblclick();
  await page.locator('textarea').fill('结构参考：保留短袖\n面料参考：棉麻');
  await page.locator('textarea').press('Escape');
  assert.equal((await state()).metadata.content, '结构参考：保留短袖\n面料参考：棉麻');
  assert.equal(await page.locator('textarea').count(), 0);
  report.checks.push('Source onDoubleClick/onChange/Escape update node metadata.');
  await page.getByTitle('选择颜色', { exact: true }).click();
  await page.getByTitle('#a7f3d0', { exact: true }).click();
  assert.equal((await state()).metadata.pluginColor, '#a7f3d0');
  report.checks.push('Source preset color button commits metadata.');
  await page.getByTitle('选择颜色', { exact: true }).click();
  await page.locator('input[type=color]').fill('#123456');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#metadata').textContent).metadata.pluginColor === '#123456');
  report.checks.push('Source custom-color timer commits the preview color.');
  await page.locator('#outside').click();
  assert.equal(await page.locator('input[type=color]').count(), 0);
  await page.locator('#plugin-node').dblclick(); await page.locator('#outside').click();
  assert.equal(await page.locator('textarea').count(), 0);
  report.checks.push('Source capture-phase outside pointer closes editor/palette.');
  await page.getByRole('button', { name: '保存测试节点', exact: true }).click();
  await page.reload(); await page.getByText('结构参考：保留短袖', { exact: false }).first().waitFor();
  assert.equal((await state()).metadata.pluginColor, '#123456');
  report.checks.push('Actual plugin consumes metadata restored by the explicitly marked host storage adapter.');
  await page.getByRole('button', { name: '卸载插件', exact: true }).click();
  await page.getByRole('button', { name: '重新挂载', exact: true }).click();
  assert.match(await page.locator('#plugin-node').innerText(), /保留短袖/);
  report.checks.push('Unmount/remount works without a duplicate React hook error.');
  assert.deepEqual(report.errors, []); assert.deepEqual(report.external, []);
  await page.screenshot({ path: path.join(root, 'qa', 'sdk-source-browser.png'), fullPage: true });
  report.passed = true;
} catch (error) { report.failure = String(error.stack || error); process.exitCode = 1; await page.screenshot({ path: path.join(root, 'qa', 'sdk-source-failure.png') }); }
finally { await fs.writeFile(path.join(root, 'qa', 'sdk-browser-results.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report)); await browser.close(); }
