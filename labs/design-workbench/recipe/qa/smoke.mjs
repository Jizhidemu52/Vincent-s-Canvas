import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const testDirectory=path.dirname(fileURLToPath(import.meta.url));
const directory=path.join(testDirectory,'output');
await fs.mkdir(directory,{recursive:true});
const origin=new URL(process.env.DESIGN_DEMO_TEST_URL || 'http://127.0.0.1:4328').origin;
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE || undefined});
const context=await browser.newContext({viewport:{width:1512,height:1050},acceptDownloads:true});
const page=await context.newPage();
const errors=[];const checks=[];const networkErrors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('requestfailed',request=>networkErrors.push({url:request.url(),error:request.failure()?.errorText}));
page.on('response',response=>{if(response.status()>=400)networkErrors.push({url:response.url(),status:response.status()});});
try {
  await page.goto(origin+'/demo/recipe',{waitUntil:'networkidle'});
  await page.locator('#recipe-kind').waitFor();
  checks.push('独立页面与默认配方成功加载');
  await page.locator('#recipe-failure').check();
  await page.locator('[data-action="run"]').click();
  await page.locator('[data-action="pause"]').click();
  await page.waitForTimeout(850);
  assert.match(await page.locator('.recipe-state').innerText(),/已暂停/);
  assert.equal(await page.locator('.recipe-result-visual img').count(),0);
  await page.locator('[data-action="resume"]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-action="retry"]').disabled,{},{timeout:20000});
  assert.match(await page.locator('[data-log="variant-1"]').innerText(),/完成 · 1 次/);
  assert.match(await page.locator('[data-log="variant-2"]').innerText(),/失败 · 1 次/);
  assert.match(await page.locator('[data-log="variant-3"]').innerText(),/完成 · 1 次/);
  await page.screenshot({path:path.join(directory,'recipe-failure.png'),fullPage:true});
  await page.locator('[data-action="retry"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-node="board"]')?.classList.contains('completed'),{},{timeout:20000});
  assert.match(await page.locator('[data-log="variant-1"]').innerText(),/完成 · 1 次/);
  assert.match(await page.locator('[data-log="variant-2"]').innerText(),/完成 · 2 次/);
  assert.match(await page.locator('[data-log="variant-3"]').innerText(),/完成 · 1 次/);
  assert.match(await page.locator('.recipe-monitor').innerText(),/¥3.20/);
  assert.match(await page.locator('.recipe-result-badge').first().innerText(),/本地示意 · 非人工智能效果/);
  checks.push('真实暂停继续、故障注入、只重试失败分支与执行次数正确');
  await page.locator('[data-action="pick"][data-id="variant-2"]').click();
  assert.equal(await page.locator('.recipe-result.selected').count(),2);
  const pngDownload=page.waitForEvent('download');await page.locator('[data-action="export-board"]').click();
  const png=await pngDownload;await png.saveAs(path.join(directory,'exported-board.png'));
  await page.waitForFunction(()=>document.querySelector('#lab-toast')?.textContent.includes('保留非人工智能标记'));
  const jsonDownload=page.waitForEvent('download');await page.locator('[data-action="export-json"]').click();
  const json=await jsonDownload;await json.saveAs(path.join(directory,'exported-workflow.json'));
  const data=JSON.parse(await fs.readFile(path.join(directory,'exported-workflow.json'),'utf8'));
  assert.equal(data.costs.actual,0);assert.equal(data.costs.attempted,3.2);assert.equal(data.selection.length,2);
  assert.ok(data.source.dataURL.startsWith('data:image/png;base64,'));
  assert.equal(data.tasks.find(task=>task.id==='variant-2').attempts,2);
  assert.ok(data.tasks.filter(task=>task.id.startsWith('variant-')).every(task=>task.output.image.startsWith('data:image/png;base64,')));
  const pngBuffer=await fs.readFile(path.join(directory,'exported-board.png'));assert.equal(pngBuffer.subarray(1,4).toString(),'PNG');
  checks.push('候选选择、方案板 PNG 和完整流程 JSON 真正下载并验签');
  await page.screenshot({path:path.join(directory,'recipe-completed.png'),fullPage:true});
  const name=await page.locator('#recipe-series').inputValue();
  await page.locator('[data-action="save"]').click();
  await page.waitForFunction(()=>document.querySelector('#lab-toast')?.textContent.includes('已保存'));
  await page.locator('#recipe-series').fill('修改参数后不可复用旧结果');
  assert.equal(await page.locator('.recipe-result-visual img').count(),0);
  assert.equal(await page.locator('[data-action="export-board"]').isDisabled(),true);
  await page.locator('[data-action="restore"]').click();
  await page.waitForFunction(expected=>document.querySelector('#recipe-series').value===expected,name);
  assert.equal(await page.locator('.recipe-result-visual img').count(),0);
  checks.push('参数编辑立即清除过期结果；IndexedDB 配方保存恢复通过');
  await page.locator('#recipe-upload').setInputFiles(path.resolve(testDirectory,'../../assets/garment.png'));
  await page.waitForFunction(()=>document.querySelector('[data-source-name]').textContent.includes('garment.png'));
  await page.locator('#recipe-upload').setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from('not an image')});
  await page.waitForFunction(()=>document.querySelector('#lab-toast')?.textContent.includes('PNG'));
  assert.match(await page.locator('[data-source-name]').innerText(),/garment.png/);
  checks.push('上传真实图片成功；不支持的文件被拒绝且保留当前输入');
  await page.locator('#recipe-kind').selectOption('pattern');
  await page.locator('#recipe-count').selectOption('2');
  await page.locator('#recipe-failure').uncheck();
  await page.locator('[data-action="run"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-node="board"]')?.classList.contains('completed'),{},{timeout:20000});
  assert.equal(await page.locator('.recipe-result-visual img').count(),2);
  await page.waitForFunction(()=>!document.querySelector('#lab-toast')||document.querySelector('#lab-toast').hidden);
  await page.screenshot({path:path.join(directory,'recipe-pattern.png'),fullPage:true});
  checks.push('图案定位配方正常产生两个本地叠加候选');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(directory,'recipe-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
  assert.equal(overflow,false);
  checks.push('390 px 窄屏无横向溢出');
  assert.deepEqual(errors,[]);
  assert.deepEqual(networkErrors,[]);
  await fs.writeFile(path.join(directory,'results.json'),JSON.stringify({passed:true,checks,errors,networkErrors,at:new Date().toISOString()},null,2));
  console.log(JSON.stringify({passed:true,checks,errors,networkErrors},null,2));
} catch(error) {
  let taskErrors=[];
  try {
    const button=page.locator('[data-action="export-json"]');
    if(await button.isEnabled()){
      const waiting=page.waitForEvent('download',{timeout:5000});await button.click();const downloaded=await waiting;
      const file=path.join(directory,'unexpected-failure-workflow.json');await downloaded.saveAs(file);
      const workflow=JSON.parse(await fs.readFile(file,'utf8'));taskErrors=workflow.tasks.map(task=>({id:task.id,status:task.status,error:task.error}));
    }
  }catch(diagnosticError){taskErrors.push({diagnosticError:String(diagnosticError)});}
  const result={passed:false,checks,errors,networkErrors,taskErrors,error:String(error.stack||error),at:new Date().toISOString()};
  await page.screenshot({path:path.join(directory,'recipe-unexpected-failure.png'),fullPage:true});
  await fs.writeFile(path.join(directory,'results.json'),JSON.stringify(result,null,2));
  await fs.writeFile(path.join(directory,'unexpected-failure.json'),JSON.stringify(result,null,2));
  console.error(JSON.stringify(result,null,2));process.exitCode=1;
} finally { await context.close();await browser.close(); }
