export function buildSolPromptRecipeContent(key: string, currentContent: PromptRecipeVersionContent): PromptRecipeVersionContent {
  if (key === "creative-chat" || key === "canvas-assistant") return structuredClone(currentContent);
  if (!Object.hasOwn(scenes, key)) throw new Error(`Unsupported Sol prompt recipe: ${key}`);
  const rules = scenes[key as PromptScene];
  return {
    ...structuredClone(currentContent),
    ...rules,
    changeNote: `适配 ${SOL_PROMPT_MODEL_ID}：逐场景重写；保留字段、语言、参考分工与目标模型覆盖；确定性模板优先，其余最小改写；反推和视频独立输出契约。`,
  };
}
